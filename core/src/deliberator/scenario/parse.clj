(ns deliberator.scenario.parse
  "Scenario text to data. `(parse text-or-bytes & {:keys [path kinds]}) -> {:header {:env :vars
  [{:name :value :line}]} :steps [{:n :kind :verb :target :name :directives [{:name :value :line}]
  :body :body-file :body-range :line}]}`; errors are thrown as `{:type :scenario/parse :line :message}`
  (message prefixed `line N: `).

  Structure is read from the file's bytes (UTF-8 for names and values), bodies are returned as the
  original bytes, so a payload round-trips exactly.

  Header (before the first step): blank lines, plain `#` comments, `# @env <name>` (once) and
  `# @var <name> = <value>`; anything else is an error. A step starts at a line beginning at column
  0 with `### ` and a kind word: `### <kind> [<verb>] [<target>] [<name>]` (a `###` line that is
  indented, quoted or has no kind word is body). The words after the kind are split with the
  help of the kind map when `:kinds` (a map kind-name -> kind map, normally
  `kinds/registry`) is given: a first word in the kind's `:verbs` is the verb; a lone word is the
  target when the kind says `:target :required`, or (`:optional`, default) when it looks like one
  (contains `/` or `://`, or starts with `{{`), else the name; two words are target and name. With
  `:kinds` an unknown kind, a missing verb or an undeclared directive is an error with the line;
  without it nothing is checked against kinds. `# @name x` overrides the name.

  Directives are the lines `# @name value` right after the step line (blank lines and plain `#` comment
  lines between them are skipped: prose about the step; for a `shell` or `sql` step such
  comment lines earn a warning, since a shebang or a script comment written there is not in the body:
  `:warnings [{:line :message :step}]` on the step and on the result). The BODY runs from after the last
  directive or comment line of that block (right after the step line when there is none) to the next `###` step line or EOF, with trailing blank lines removed but the newline of
  the last non-blank line kept: `{...}\\n\\n###` yields `{...}\\n`, `{...}` at EOF without a newline
  yields `{...}`. A separator blank line is layout, not payload (the PoC lost final newlines the
  other way round). Who needs other bytes, trailing blank lines included, uses `# @body <file>`:
  the file's bytes, read relative to `:path`'s directory (absolute paths allowed), always
  byte-exact; without `:path` only `:body-file` is recorded. A file body together with a non-blank
  inline body is an error, and so is an engine-owned directive line (`assert capture until timeout
  body name`) found inside the body (it would otherwise be silently sent). `:body` is a byte array
  or nil; `:body-range` the `[from to)` byte offsets of the inline body in the source.

  Region markers: a line at column 0 that starts with `#>` opens, one that starts with `#<` closes a region
  of steps that the `ai` block above it generated (`#> generated by haiku ...` ... `#< end`). They are layout: before
  anything is parsed their text is blanked (same bytes, same offsets), so they are never part of a body, a directive or
  the prose. They must pair (an open one is closed before the next open one, a close one has an open one) and only blank
  or `#` lines may follow a close marker before the next step. A marker inside an open JSON string of a body is body.
  `:markers [{:line :open? :text}]` on the result lists them."
  (:require [clojure.string :as str]
            [deliberator.scenario.kinds :as kinds])
  (:import (java.nio.charset StandardCharsets)
           (java.nio.file Files Path Paths)))

(defn- perr [line msg]
  (throw (ex-info (str "line " line ": " msg)
                  {:type :scenario/parse :line line :message msg})))

(defn- ->bytes ^bytes [x]
  (if (string? x) (.getBytes ^String x StandardCharsets/UTF_8) x))

(defn- u8 [^String latin1]
  (String. (.getBytes latin1 StandardCharsets/ISO_8859_1) StandardCharsets/UTF_8))

(defn- split-lines
  "Vector of {:no :start :next :text} over the latin-1 view; :text without the \\n and a trailing \\r."
  [^String s]
  (let [n (count s)]
    (loop [start 0 no 1 out (transient [])]
      (if (>= start n)
        (persistent! out)
        (let [nl (.indexOf s "\n" (int start))
              end (if (neg? nl) n nl)
              nxt (if (neg? nl) n (inc nl))
              text (let [t (subs s start end)] (if (str/ends-with? t "\r") (subs t 0 (dec (count t))) t))]
          (recur nxt (inc no) (conj! out {:no no :start start :next nxt :text text})))))))

(def ^:private step-re #"### +([A-Za-z][A-Za-z0-9_-]*)(?:\s+(.*?))?\s*")
(def ^:private directive-re #"#\s*@([A-Za-z][A-Za-z0-9._-]*)(?:\s+(.*?))?\s*")
(def ^:private engine-names (set (map :name kinds/engine-directives)))
(def ^:private engine-body-re
  (re-pattern (str "#\\s*@(" (str/join "|" (sort engine-names)) ")(\\s.*)?\\s*")))

(def ^:private script-kinds
  "Kinds whose body is a script in which a `#` line means something (a shebang, a comment): a `#` line
  swallowed as prose before such a body is worth a warning (review 2026-10-25, R10)."
  #{"shell" "sql"})

(defn- blank? [{:keys [text]}] (str/blank? text))
(defn- comment-line? [{:keys [text]}] (and (str/starts-with? text "#") (not (str/starts-with? text "###"))))

(defn- scan-json
  "Advances the JSON scanner `{:depth :in-str}` over one line of body text. A JSON value opens only
  at a `{`/`[` that starts its line, so a brace inside a SQL literal or prose never starts string
  tracking."
  [{:keys [depth in-str] :as st} ^String text]
  (let [n (count text)]
    (loop [i 0 depth depth in-str in-str]
      (if (>= i n)
        {:depth depth :in-str in-str}
        (let [c (.charAt text i)]
          (cond
            in-str (cond (= c \\) (recur (+ i 2) depth true)
                         (= c \") (recur (inc i) depth false)
                         :else (recur (inc i) depth true))
            (zero? depth) (if (and (or (= c \{) (= c \[)) (str/blank? (subs text 0 i)))
                           (recur (inc i) 1 false)
                           (recur (inc i) 0 false))
            (= c \") (recur (inc i) depth true)
            (or (= c \{) (= c \[)) (recur (inc i) (inc depth) false)
            (or (= c \}) (= c \])) (recur (inc i) (dec depth) false)
            :else (recur (inc i) depth false)))))))

(def ^:private marker-re #"#[<>].*")

(defn- find-heads
  "Indexes of the step header lines. A `### kind` line inside a JSON string of the body (a string
  opened and not yet closed, within a `{`/`[` value) is body. If such a string is never closed
  before the end of the file the rule is dropped from that line on (a stray quote must not swallow
  the rest of the file). Also the region marker lines (`marker-re`, outside an open JSON string). -> `{:heads [i..] :markers [i..]}`."
  [lines]
  (let [n (count lines)]
    (loop [i 0 st {:depth 0 :in-str false} skipped nil out [] mk #{}]
      (if (>= i n)
        (if (and (:in-str st) skipped)
          (recur (inc skipped) {:depth 0 :in-str false} nil (conj out skipped) mk)
          {:heads out :markers (vec (sort mk))})
        (let [{:keys [text]} (nth lines i)
              head? (re-matches step-re text)]
          (cond
            (and head? (:in-str st)) (recur (inc i) st (or skipped i) out mk)
            head? (recur (inc i) {:depth 0 :in-str false} nil (conj out i) mk)
            (str/starts-with? text "#") (recur (inc i) st skipped out
                                               (if (and (not (:in-str st)) (re-matches marker-re text)) (conj mk i) mk))
            :else (let [st' (scan-json st text)]
                    (recur (inc i) st' (if (:in-str st') skipped nil) out mk))))))))

(defn- directive [{:keys [text no]}]
  (when-let [[_ n v] (re-matches directive-re text)]
    {:name n :value (u8 (or v "")) :line no}))

(defn- parse-header [lines]
  (reduce
   (fn [h {:keys [text no] :as l}]
     (cond
       (blank? l) h
       (str/starts-with? text "#")
       (if-let [{:keys [name value]} (directive l)]
         (case name
           "env" (do (when (:env h) (perr no "duplicate @env"))
                     (when (str/blank? value) (perr no "@env needs a name"))
                     (assoc h :env value))
           "var" (if-let [[_ n v] (re-matches #"([A-Za-z_][A-Za-z0-9_.-]*)\s*=\s*(.*)" value)]
                   (update h :vars conj {:name n :value v :line no})
                   (perr no "@var needs `name = value`"))
           (perr no (str "unknown header directive @" name " (header has @env and @var)")))
         h)
       (str/starts-with? text "//") h
       :else (perr no (str "unexpected text before the first ### step: " (pr-str (u8 text))))))
   {:env nil :vars []}
   lines))

(defn- target-like? [w]
  (or (str/includes? w "/") (str/starts-with? w "{{")))

(defn- verb-error
  "The `needs a verb` message. A short verb list is printed whole; a long one of `service.Operation` verbs (the aws kind:
  thousands) names the services, or the close operations of a known service."
  [kind word real]
  (if (<= (count real) 100)
    (str kind " needs a verb: " (str/join " | " (sort real)))
    (let [[svc op] (some-> word (str/split #"\." 2))
          services (into (sorted-set) (map #(first (str/split % #"\." 2))) real)
          close (fn [xs w] (let [w (str/lower-case (str w))
                                 p (subs w 0 (min 4 (count w)))]
                             (filter #(let [x (str/lower-case %)]
                                        (or (str/includes? x w) (str/includes? w x) (and (seq p) (str/starts-with? x p))))
                                     xs)))]
      (if (and op (contains? services svc))
        (let [ops (sort (keep #(when (str/starts-with? % (str svc ".")) (subs % (inc (count svc)))) real))
              near (take 12 (close ops op))]
          (str kind " has no verb " word ": " svc " has " (count ops) " operations"
               (when (seq near) (str ", close: " (str/join " | " (map #(str svc "." %) near))))))
        (let [near (when svc (seq (close services svc)))]
          (str kind " needs a verb service.Operation" (when word (str ", not " word))
               (when near (str "; did you mean " (str/join " or " near) "?"))
               " services: " (str/join " " services)))))))

(defn- split-words [no kind words kmap]
  (let [verbs (if kmap (:verbs kmap #{nil}) #{nil})
        real (disj verbs nil)
        [verb words] (if (and (seq words)
                              (if kmap
                                (contains? real (first words))
                                (and (>= (count words) 2) (not (target-like? (first words)))
                                     (target-like? (second words)))))
                       [(first words) (rest words)]
                       (do (when (and kmap (not (contains? verbs nil)))
                             (perr no (verb-error kind (first words) real)))
                           [nil words]))
        mode (if kmap (:target (kinds/for-verb kmap verb) :optional) :optional)
        n (count words)]
    (when (> n 2) (perr no (str "too many words in the step line after " kind " (verb target name)")))
    (let [[target name]
          (case n
            0 [nil nil]
            1 (if (and (not= mode :none) (or (= mode :required) (target-like? (first words))))
                [(first words) nil]
                [nil (first words)])
            2 [(first words) (second words)])]
      (when (and kmap (= mode :required) (nil? target))
        (perr no (str kind (when verb (str " " verb)) " needs a target")))
      {:verb verb :target target :name name})))

(defn- parse-step [^bytes bs ^String s n lines hi end-start ^Path path kinds]
  (let [{h-text :text no :no} (nth lines hi)
        [_ kind rest-words] (re-matches step-re h-text)
        words (if (str/blank? rest-words) [] (vec (str/split (str/trim rest-words) #"\s+")))
        kmap (when kinds
               (or (get kinds kind)
                   (perr no (str "unknown step kind " (pr-str kind) "; known: "
                                 (str/join ", " (sort (keys kinds)))))))
        {:keys [verb target name]} (split-words no kind (map u8 words) kmap)
        ;; directives
        [dirs last-i prose]
        (loop [i (inc hi) dirs [] last-i hi prose []]
          (if-let [l (and (< i end-start) (nth lines i))]
            (cond
              (blank? l) (recur (inc i) dirs last-i prose)
              (directive l) (recur (inc i) (conj dirs (directive l)) i prose)
              (comment-line? l) (recur (inc i) dirs i (conj prose l))   ; prose about the step, among its directives
              :else [dirs last-i prose])
            [dirs last-i prose]))
        warnings (when (and (seq prose) (contains? script-kinds kind))
                   [{:line (:no (first prose)) :step n
                     :message (str (count prose) " comment line" (when (> (count prose) 1) "s") " before the body of this " kind
                                   " step " (if (> (count prose) 1) "are" "is") " prose about the step, not part of the script"
                                   " (a `#` line right after the step line or its directives is a comment);"
                                   " start the body with a non-# line (`:` or `true` in bash) to keep a shebang or comment in it")}])
        allowed (when kmap (set (map :name (kinds/directive-specs (kinds/for-verb kmap verb)))))
        _ (when allowed
            (doseq [{dn :name dl :line} dirs]
              (when-not (contains? allowed dn)
                (perr dl (str "unknown directive @" dn " for " kind "; known: "
                              (str/join ", " (map #(str "@" %) (sort allowed))))))))
        body-from-i (inc last-i)
        body-start (if (< body-from-i (count lines)) (:start (nth lines body-from-i)) (count s))
        body-start (min body-start (if (< end-start (count lines)) (:start (nth lines end-start)) (count s)))
        region-end (if (< end-start (count lines)) (:start (nth lines end-start)) (count s))
        ;; strip trailing blank lines
        end-i (loop [j (dec end-start)]
                (if (and (>= j body-from-i) (blank? (nth lines j))) (recur (dec j)) j))
        body-end (if (< end-i body-from-i) body-start (:next (nth lines end-i)))
        body-end (min body-end region-end)
        inline? (> body-end body-start)
        _ (doseq [j (range body-from-i (inc (max end-i (dec body-from-i))))
                  :let [l (nth lines j)]
                  :when (re-matches engine-body-re (:text l))]
            (perr (:no l) (str "directive after the body: " (pr-str (u8 (:text l)))
                               " (directives go right after the ### line)")))
        body-file (some #(when (= "body" (:name %)) (:value %)) dirs)
        body-dir (some #(when (= "body" (:name %)) %) dirs)
        _ (when (and body-dir (str/blank? body-file)) (perr (:line body-dir) "@body needs a file"))
        _ (when (and body-file inline?) (perr (:line body-dir) "@body together with an inline body"))
        body (cond
               inline? (java.util.Arrays/copyOfRange bs (int body-start) (int body-end))
               (and body-file path)
               (let [p (.resolve (or (.getParent (.toAbsolutePath path)) (Paths/get "." (make-array String 0)))
                                 ^String body-file)]
                 (if (Files/isRegularFile p (make-array java.nio.file.LinkOption 0))
                   (Files/readAllBytes p)
                   (perr (:line body-dir) (str "@body file not found: " body-file))))
               :else nil)
        name (or (some #(when (= "name" (:name %)) (:value %)) dirs) name)]
    (cond-> {:n n :kind kind :verb verb :target target :name name :directives dirs :line no
             :body body}
      body-file (assoc :body-file body-file)
      inline? (assoc :body-range [body-start body-end])
      (seq warnings) (assoc :warnings (vec warnings)))))

(defn- check-markers!
  "The markers (line indexes) pair up: open, close, open, close...; after a close marker only blank or `#` lines
  until the next step head."
  [lines markers heads]
  (let [open? #(str/starts-with? (:text (nth lines %)) "#>")
        no #(:no (nth lines %))]
    (loop [[m & more] markers expect-open true]
      (cond
        (nil? m) (when-not expect-open
                   (perr (no (last markers)) "region opened with `#>` is never closed (`#< end`)"))
        (and expect-open (not (open? m))) (perr (no m) "`#<` without an open `#>` region")
        (and (not expect-open) (open? m)) (perr (no m) "`#>` inside a region that is not closed yet (`#< end`)")
        :else
        (do (when-not expect-open
              (let [nxt (or (first (filter #(> % m) heads)) (count lines))]
                (doseq [j (range (inc m) nxt)
                        :let [t (:text (nth lines j))]
                        :when (not (or (str/blank? t) (str/starts-with? t "#")))]
                  (perr (no j) "text after `#< end`: the region ends the steps of the block above it; start a step with ### or remove the text"))))
            (recur more (not expect-open)))))))

(defn- blank-lines
  "A copy of `bs` with the text of the given lines replaced by spaces: same length, same newlines."
  ^bytes [^bytes bs lines idxs]
  (let [out (aclone bs)]
    (doseq [i idxs
            :let [{:keys [start text]} (nth lines i)]
            k (range (count text))]
      (aset-byte out (+ start k) (byte 32)))
    out))

(defn parse
  [text & {:keys [path kinds]}]
  (let [bs0 (->bytes text)
        lines0 (split-lines (String. bs0 StandardCharsets/ISO_8859_1))
        {:keys [heads markers]} (find-heads lines0)
        _ (check-markers! lines0 markers heads)
        bs (if (seq markers) (blank-lines bs0 lines0 markers) bs0)
        s (String. bs StandardCharsets/ISO_8859_1)
        lines (if (seq markers) (split-lines s) lines0)
        path (when path (if (instance? Path path) path (Paths/get (str path) (make-array String 0))))
        first-head (or (first heads) (count lines))
        header (parse-header (subvec lines 0 first-head))
        ends (conj (vec (rest heads)) (count lines))
        steps (vec (map-indexed
                    (fn [k [hi end]] (parse-step bs s (inc k) lines hi end path kinds))
                    (map vector heads ends)))]
    {:header header
     :steps steps
     :markers (vec (for [i markers :let [t (:text (nth lines0 i))]]
                     {:line (:no (nth lines0 i)) :open? (str/starts-with? t "#>") :text (u8 t)}))
     :warnings (vec (mapcat :warnings steps))}))

(defn- ai-info
  "`:ai` of an `ai` step in `describe`: where its prose ends and the region its steps sit in."
  [lines step-line end-line markers]
  (let [open (first (filter #(and (:open? %) (< step-line (:line %)) (<= (:line %) end-line)) markers))
        close (when open (first (filter #(and (not (:open? %)) (> (:line %) (:line open))) markers)))
        limit (if open (dec (:line open)) end-line)
        prose-end (loop [l (min limit (count lines))]
                    (if (and (> l step-line) (str/blank? (nth lines (dec l)))) (recur (dec l)) l))]
    (cond-> {:prose-end-line prose-end}
      open (assoc :region {:from-line (:line open) :to-line (:line close) :header (:text open)}))))

(defn describe
  "Parse for editors (`scenario.parse`): `{:header {:env :vars [{:name :value :line}]} :steps [{:index
  :kind :verb :target :name :line :end-line :directives [{:name :value :line}] :body-lines :body-line
  :body-file}] :errors [{:line :message}]}` over `text` with the registered kinds. A syntax error is data,
  not a throw: `:errors` holds it and `:steps` is empty (the parser stops at the first error).
  `:body-lines` counts the inline body's lines, `:body-line` is its first line (1-based);
  `:end-line` is the line before the next step (or the last line). An `ai` step also has `:ai {:prose-end-line
  :region {:from-line :to-line :header}}` (lines of the `#>` and `#< end` markers of the steps it generated, absent
  when it has none). `path` only resolves `# @body`."
  [text & {:keys [path kinds]}]
  (try
    (let [bs (->bytes text)
          s (String. bs StandardCharsets/UTF_8)
          total (count (str/split-lines s))
          total (if (str/ends-with? s "\n") total (max total 1))
          line-at (fn [off] (inc (count (filter #(= \newline %)
                                                (String. bs 0 (int off) StandardCharsets/ISO_8859_1)))))
          {:keys [header steps warnings markers]} (parse bs :path path :kinds kinds)
          lines (vec (str/split-lines s))
          ends (conj (mapv #(dec (:line %)) (rest steps)) (max total (or (:line (last steps)) 1)))]
      {:header {:env (:env header)
                :vars (mapv #(select-keys % [:name :value :line]) (:vars header))}
       :warnings (vec warnings)
       :steps (vec (map-indexed
                    (fn [i st]
                      (let [[from to] (:body-range st)]
                        (cond-> {:index (:n st) :kind (:kind st) :verb (:verb st) :target (:target st)
                                 :name (:name st) :line (:line st) :end-line (nth ends i)
                                 :directives (mapv #(select-keys % [:name :value :line]) (:directives st))
                                 :body-lines (if from
                                               (count (str/split-lines (String. bs (int from) (int (- to from)) StandardCharsets/ISO_8859_1)))
                                               0)}
                          from (assoc :body-line (line-at from))
                          (:body-file st) (assoc :body-file (:body-file st))
                          (= "ai" (:kind st)) (assoc :ai (ai-info lines (:line st) (nth ends i) markers)))))
                    steps))
       :errors []})
    (catch clojure.lang.ExceptionInfo e
      (if (= :scenario/parse (:type (ex-data e)))
        (let [d (ex-data e)]
          {:header nil :steps [] :warnings []
           :errors [{:line (:line d) :message (or (:message d) (ex-message e))}]})
        (throw e)))))
