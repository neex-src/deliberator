(def ^:private no-endpoint
  "Types that never call AWS."
  #{"aws_iam_policy_document" "aws_partition" "aws_region"})

(defn endpoint-key
  "The provider `endpoints` key of Terraform type `t` (`aws_sqs_queue` -> \"sqs\"), nil when none is known."
  [t]
  (when (and (str/starts-with? t "aws_") (not (no-endpoint t)))
    (let [rest (subs t 4)]
      (some (fn [[p k]] (when (or (= rest p) (str/starts-with? rest (str p "_"))) k)) service-prefixes))))

;; analysis ---------------------------------------------------------------------------------------

(defn- canonical ^File [dir] (.getCanonicalFile (io/file (str dir))))

(def ^:private ident-attrs ["name" "function_name" "bucket" "cluster_name" "queue_name" "table_name"])

(defn- ident-of [b] (some #(hcl/lit b %) ident-attrs))

(defn analyse
  "`{:dir :providers [{:alias :block :file :line}] :module-providers [{:dir :line}] :backend {:kind :s3|:local|:other …}
  :services #{endpoint-key} :unmapped #{type} :emulator? :remote-states [{:name :backend :config :file :line}]
  :declares [{:type :ident :file :line}] :lookups [{:type :ident :file :line}]}` of the root `dir`."
  [dir]
  (let [d (.getPath (canonical dir))
        tr (hcl/tree d)
        all (mapcat (fn [{:keys [dir blocks]}] (map #(assoc % :dir dir) blocks)) tr)
        root-blocks (:blocks (first tr))
        providers (vec (for [b root-blocks :when (and (= "provider" (:type b)) (= ["aws"] (:labels b)))]
                         {:alias (hcl/lit b "alias") :block b :file (:file b) :line (:line b)}))
        module-providers (vec (for [{md :dir blocks :blocks} (rest tr) b blocks
                                    :when (and (= "provider" (:type b)) (= ["aws"] (:labels b)))]
                                {:dir md :line (:line b) :file (:file b)}))
        backend (let [tf (first (filter #(= "terraform" (:type %)) root-blocks))
                      be (first (filter #(= "backend" (:type %)) (:blocks tf)))
                      cfg (fn [k] (hcl/lit be k))]
                  (cond
                    (nil? be) {:kind :local :path (str (io/file d "terraform.tfstate")) :implicit true}
                    (= ["s3"] (:labels be)) {:kind :s3 :bucket (cfg "bucket") :key (cfg "key")}
                    (= ["local"] (:labels be)) {:kind :local :path (str (.getCanonicalFile (io/file d (or (cfg "path") "terraform.tfstate"))))}
                    :else {:kind :other :type (first (:labels be))}))
        typed (fn [kind] (filter #(and (= kind (:type %)) (seq (:labels %))) all))
        types (concat (map (comp first :labels) (typed "resource")) (map (comp first :labels) (typed "data")))
        mapped (map (juxt identity endpoint-key) (distinct types))]
    {:dir d :providers providers :module-providers module-providers :backend backend
     :services (into #{} (keep second) mapped)
     :unmapped (into (sorted-set) (comp (filter #(and (str/starts-with? (first %) "aws_") (not (no-endpoint (first %))) (nil? (second %)))) (map first)) mapped)
     :emulator? (boolean (and (seq providers)
                              (every? (fn [{:keys [block]}]
                                        (and (some #(= "endpoints" (:type %)) (:blocks block))
                                             (some? (hcl/lit block "access_key"))
                                             (true? (hcl/bool block "skip_requesting_account_id"))))
                                      providers)))
     :remote-states (vec (for [b (typed "data") :when (= ["terraform_remote_state"] (take 1 (:labels b)))]
                           {:name (second (:labels b)) :backend (hcl/lit b "backend")
                            :config (into {} (keep (fn [[k v]] (when (:lit v) [k (:lit v)]))) (get-in b [:attrs "config" :obj]))
                            :dir (:dir b) :file (:file b) :line (:line b)}))
     :declares (vec (for [b (typed "resource") :when (ident-of b)]
                      {:type (first (:labels b)) :ident (ident-of b) :file (:file b) :line (:line b)}))
     :lookups (vec (for [b (typed "data") :when (and (str/starts-with? (first (:labels b)) "aws_") (ident-of b))]
                     {:type (first (:labels b)) :ident (ident-of b) :file (:file b) :line (:line b)}))}))

;; state ------------------------------------------------------------------------------------------

(defn root-id
  "`<basename>-<8 hex of the sha256 of the absolute path>`: the name of the root's place under the workspace's `terraform/`."
  [dir]
  (let [p (.getPath (canonical dir))]
    (str (str/replace (.getName (io/file p)) #"[^A-Za-z0-9._-]" "_") "-"
         (subs (store/sha256 (.getBytes ^String p "UTF-8")) 0 8))))

(defn state-dir [ws dir] (store/path ws "terraform" (root-id dir)))
(defn state-path
  "Where the local state of root `dir` lives while Deliberator runs it: under the workspace, never in the user's checkout."
  [ws dir] (str (.resolve (state-dir ws dir) "terraform.tfstate")))
(defn data-dir
  "`TF_DATA_DIR` of root `dir`: `.terraform` of the user's checkout (backend metadata of the real one) stays as it is."
  [ws dir] (str (.resolve (state-dir ws dir) "data")))

;; graph ------------------------------------------------------------------------------------------

(defn- root-names
  "dir -> short name: the basename, the last two path segments when two roots share one."
  [dirs]
  (let [base (fn [d] (.getName (io/file d)))
        dup (into #{} (comp (map base) (filter (fn [b] (< 1 (count (filter #(= b (base %)) dirs)))))) dirs)]
    (into {} (for [d dirs]
               [d (if (dup (base d))
                    (let [f (io/file d)] (str (some-> (.getParentFile f) .getName) "/" (.getName f)))
                    (base d))]))))

(defn- match-remote-state
  "The info of the root that holds the state `rs` of root `r` reads, among `others`, or nil."
  [r rs others]
  (let [cfg (:config rs)]
    (case (:backend rs)
      "s3" (when-let [k (get cfg "key")]
             (first (filter (fn [o] (let [b (:backend o)]
                                      (and (= :s3 (:kind b)) (= k (:key b))
                                           (or (nil? (:bucket b)) (nil? (get cfg "bucket")) (= (:bucket b) (get cfg "bucket"))))))
                            others)))
      "local" (when-let [p (get cfg "path")]
                (let [abs (.getPath (.getCanonicalFile (io/file (:dir r) p)))]
                  (first (filter #(= abs (get-in % [:backend :path])) others))))
      nil)))

(defn graph
  "`roots` (directories) -> `{:roots [{:name :dir}] :edges [{:from :to :via :ref :file :line}] :order [dir] :unresolved [..]}`:
  an edge `from -> to` says `to` must be applied after `from` because `to` reads the state of `from` (`:via \"remote_state\"`) or
  looks up (`data`) a resource `from` declares by a literal name (`:via \"data\"`). `:order` lists the directories, dependencies
  first, otherwise in the order given. `:unresolved` lists the `terraform_remote_state` blocks that point at no given root.
  A cycle is `{:type :tf/cycle :cycle [names]}`."
  [roots]
  (let [dirs (mapv #(.getPath (canonical %)) roots)
        _ (when (not= (count dirs) (count (distinct dirs)))
            (throw (ex-info "the same root is listed twice" {:type :tf/bad-roots :roots dirs})))
        infos (mapv analyse dirs)
        names (root-names dirs)
        nm (fn [i] (names (:dir i)))
        edge (fn [from to via ref loc] (merge {:from (nm from) :to (nm to) :via via :ref ref} (select-keys loc [:file :line])))
        edges (vec (distinct
                    (for [r infos
                          e (concat
                             (for [rs (:remote-states r)
                                   :let [o (match-remote-state r rs (remove #(= (:dir r) (:dir %)) infos))]
                                   :when o]
                               (edge o r "remote_state" (str "data.terraform_remote_state." (:name rs)) rs))
                             (for [l (:lookups r)
                                   o (remove #(= (:dir r) (:dir %)) infos)
                                   :when (some #(and (= (:type l) (:type %)) (= (:ident l) (:ident %))) (:declares o))]
                               (edge o r "data" (str (:type l) " " (:ident l)) l)))]
                      e)))
        unresolved (vec (for [r infos rs (:remote-states r)
                              :when (not (match-remote-state r rs (remove #(= (:dir r) (:dir %)) infos)))]
                          {:root (nm r) :ref (str "data.terraform_remote_state." (:name rs)) :backend (:backend rs) :file (:file rs) :line (:line rs)}))
        by-name (into {} (map (juxt nm :dir)) infos)
        order (loop [done [] todo (mapv nm infos)]
                (if (empty? todo)
                  done
                  (let [ready (first (filter (fn [n] (every? (set done) (map :from (filter #(= n (:to %)) edges)))) todo))]
                    (if ready
                      (recur (conj done ready) (vec (remove #{ready} todo)))
                      (throw (ex-info (str "the roots depend on each other in a cycle: " (str/join ", " todo))
                                      {:type :tf/cycle :cycle todo :edges (filterv #(and (some #{(:from %)} todo) (some #{(:to %)} todo)) edges)}))))))]
    {:roots (mapv (fn [i] {:name (nm i) :dir (:dir i)}) infos)
     :edges edges
     :order (mapv by-name order)
     :unresolved unresolved}))

(defn remote-state-targets
  "For root `dir` among `roots`: `{remote-state-block-name state-path-of-the-root-it-reads}` (the override redirects
  those blocks to the local state of that root)."
  [ws dir roots]
  (let [r (analyse dir)
        others (map analyse (remove #(= (.getPath (canonical %)) (:dir r)) roots))]
    (into {} (keep (fn [rs] (when-let [o (match-remote-state r rs others)] [(:name rs) (state-path ws (:dir o))])))
          (:remote-states r))))

;; the override -----------------------------------------------------------------------------------

(def ^:private nulled
  "Attributes of a provider block that name real credentials or accounts: set to null in the override when the block has them."
  ["profile" "token" "shared_config_files" "shared_credentials_files" "allowed_account_ids" "forbidden_account_ids"])

(defn override-doc
  "The map written as `deliberator_override.tf.json` for the analysed root `a`: every `provider \"aws\"` block (and alias) of the root
  points its `endpoints` (the services the root uses, plus sts) at `endpoint`, with fake credentials and the skip flags; the
  backend is a local state under the workspace (`state-path`), the `terraform_remote_state` blocks that read a given root read
  its local state (`remote-states`: name -> path). The root's own `region` is kept; a block without one gets `region`."
  [a {:keys [endpoint region access-key secret-key state-path remote-states]}]
  (let [eps (into (sorted-map) (map (fn [k] [k endpoint])) (conj (:services a) "sts"))]
    (cond-> {"//" (str generated-marker ", M6.1: provider endpoints and a local state for running this root on the local runtime. "
                       "Do not commit it (gitignore). Delete this line to take the file over: it is then never rewritten.")
             "terraform" {"backend" {"local" {"path" state-path}}}}
      (seq (:providers a))
      (assoc "provider" {"aws" (vec (for [{:keys [alias block]} (:providers a)]
                                      (cond-> {"access_key" access-key "secret_key" secret-key
                                               "skip_credentials_validation" true "skip_metadata_api_check" true
                                               "skip_requesting_account_id" true "skip_region_validation" true
                                               "s3_use_path_style" true
                                               "endpoints" [eps]}
                                        alias (assoc "alias" alias)
                                        (not (contains? (:attrs block) "region")) (assoc "region" region)
                                        true (into (for [k nulled :when (contains? (:attrs block) k)] [k nil])))))})
      (seq remote-states)
      (assoc "data" {"terraform_remote_state"
                     (into (sorted-map) (for [[n p] remote-states] [n {"backend" "local" "config" {"path" p}}]))}))))

(defn generated?
  "True when the override file `f` carries the generated marker (so it may be rewritten)."
  [^File f]
  (try (let [m (json/read-str (slurp f))]
         (and (map? m) (string? (get m "//")) (str/starts-with? (get m "//") generated-marker)))
       (catch Exception _ false)))

(defn coverage-problems
  "Why the root analysed as `a` cannot run on the local runtime with override document `doc`, as a vector of strings (empty
  when it can): an `aws` provider block (by alias) the override does not carry, a provider block inside a module (an override file
  reaches only the root's), an endpoint on AWS itself, an AWS resource type with no known local endpoint."
  [a doc]
  (let [have (set (map #(get % "alias") (get-in doc ["provider" "aws"])))]
    (vec (concat
          (for [{:keys [alias line]} (:providers a) :when (not (contains? have alias))]
            (str "provider \"aws\"" (when alias (str " (alias " alias ")")) " at line " line " has no override in " override-name))
          (for [{:keys [dir line]} (:module-providers a)]
            (str "the module " dir " declares its own provider \"aws\" (line " line "): an override file cannot reach it"))
          (when (re-find #"amazonaws\.com" (json/write-str (get-in doc ["provider" "aws"])))
            [(str override-name " points a provider at amazonaws.com")])
          (when (and (empty? (:providers a)) (some #(str/starts-with? % "aws_") (map :type (concat (:declares a) (:lookups a)))))
            ["the root uses AWS resources but declares no provider \"aws\" block to override: add provider \"aws\" { region = ... }"])))))
