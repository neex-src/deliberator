(ns deliberator.tfroot
  "What a Terraform root says about itself, read from its `.tf` files by `deliberator.hcl` and never evaluated:
  its `provider \"aws\"` blocks, its state identity (backend), the AWS services its resources and data sources use, what it
  declares and what it looks up in other roots (`terraform_remote_state`, `data` of a named resource), and from those the
  override file `terraform.local` writes (M6.1), the dependency graph and the apply order of several roots (M6.3)."
  (:require [clojure.data.json :as json]
            [clojure.java.io :as io]
            [clojure.string :as str]
            [deliberator.hcl :as hcl]
            [deliberator.store :as store])
  (:import (java.io File)))

(def override-name "deliberator_override.tf.json")

(def generated-marker "Generated by Deliberator (terraform.local)")

