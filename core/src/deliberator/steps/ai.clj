(ns deliberator.steps.ai
  "Kind `ai`: `### ai <name>` and a prose body (\"log in as anna, activate a second line, check the letter\").
  It is not a step at run time: the kind is `:inert?`, the parser numbers it and `scenario.kinds` lists it, the engine skips
  it. `scenario.generate` (deliberator.generate) asks a model for the steps and puts them under the prose between the
  `#> generated by ...` and `#< end` marker lines; those steps are ordinary steps. The prose is free text, but a line of it
  must not start with `###` (a step head) or be a `# @directive` line."
  (:require [deliberator.scenario.kinds :as kinds]))

(def kind
  {:kind "ai" :verbs #{nil} :target :none :inert? true
   :directives [] :facts [] :capture-roots #{} :concurrent? false
   :run (fn [_ _] (throw (ex-info "an ai block is not a step: generate its steps with scenario.generate (dlb scenario generate FILE NAME)"
                                  {:type :ai/not-a-step})))})

(kinds/register! kind)
