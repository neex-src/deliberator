(ns deliberator.generate
  "`scenario.generate`: the prose of an `### ai <name>` block becomes steps, written by a cheap model,
  checked by Deliberator, put under the prose between the `#> generated by ...` and `#< end` marker lines.

  `(generate! ws opts) -> result`. `opts`: `:file` (the scenario path, for `# @body`), `:text` (the document as the caller
  holds it, else the file is read), `:name` (the ai block), `:env` (the environment record), `:session` (key),
  `:operations` (rows of `op.describe`), `:sink` (fn of an event map: `generate.started|attempt|checked|finished`),
  `:on-cancel!` (the protocol's), `:write?` (rewrite `:file`). Result: `{:status \"ok\" :name :model :attempts :usage :steps
  :marker :region [lines] :run :paths :wrote}`; a second wrong answer throws `{:type :generate/invalid :errors [...]}`.

  The folder `sessions/<key>/generate/<stamp>-<name>/` holds everything, each file there before anything parses it:
  `source.scn` (the document), `context/` (what the model may read: `universal.json`, `skills/`), `prompt-N.md` (stdin of
  the model command), `model-N.out` / `model-N.err` (its stdout and stderr, as they arrived), `answer-N.scn` (the steps, a
  code fence taken off), `usage-N.edn`, `check-N.edn`, `generated.scn`, `generate.edn` (status, model, attempts, total
  usage, the model's own session id, scenario path and sha).

  The model command is `workspace.edn :ai {:command [argv] :env {} :format :claude-json|:text :budget-ms n}`, merged over
  `default-ai`: run with `context/` as the working directory, the prompt on stdin, the answer on stdout. The default is
  `claude -p --model haiku` with only Read, Grep and Glob, and those only inside the folder (`Read(./**)` with
  `--permission-mode dontAsk`); user settings stay on, so the hooks of the machine (reus) see the call like any session.
  Format `:claude-json` (`--output-format json`) gives the answer in `result` and the usage in `usage`/`total_cost_usd`;
  `:text` is the bare answer, and the marker then says the usage was not reported: nothing is estimated."
  (:require [clojure.data.json :as json]
            [clojure.java.io :as io]
            [clojure.string :as str]
            [deliberator.env :as denv]
            [deliberator.process :as process]
            [deliberator.scenario.engine :as engine]
            [deliberator.scenario.kinds :as kinds]
            [deliberator.scenario.parse :as parse]
            [deliberator.session :as session]
            [deliberator.store :as store]
            [deliberator.universal :as universal]
            [deliberator.workspace :as workspace])
  (:import (java.nio.file Files FileAlreadyExistsException Path)
           (java.nio.file.attribute FileAttribute)
           (java.time ZoneOffset)
           (java.time.format DateTimeFormatter)
           (java.util.concurrent TimeUnit)))

(def system-line "You write Deliberator scenario steps from a description. Follow the request in the user message exactly.")

(def default-ai
  {:command ["claude" "-p" "--model" "haiku"
             "--tools" "Read,Grep,Glob" "--allowedTools" "Read(./**)" "--permission-mode" "dontAsk"
             "--strict-mcp-config" "--disable-slash-commands" "--setting-sources" "user"
             "--output-format" "json" "--max-budget-usd" "0.25"
             "--system-prompt" system-line]
   :env {"CLAUDE_CODE_DISABLE_CLAUDE_MDS" "1"}
   :format :claude-json
   :budget-ms 240000})

(defn ai-config "The model command of workspace `ws`: `default-ai` with `workspace.edn :ai` on top." [ws]
  (let [c (:ai (workspace/load ws))]
    (-> (merge default-ai (dissoc c :env))
        (assoc :env (merge (:env default-ai) (:env c))))))

(defn- fail [type msg & {:as data}] (throw (ex-info msg (assoc data :type type))))

(defn- ->path ^Path [p] (if (instance? Path p) p (.toPath (io/file (str p)))))

(def ^:private stamp (.withZone (DateTimeFormatter/ofPattern "yyyyMMdd-HHmmss") ZoneOffset/UTC))

;; the document ---------------------------------------------------------------------------------

(defn- split-keep [^String text] (vec (str/split text #"\n" -1)))
(defn- join-keep [lines] (str/join "\n" lines))

(defn find-block
  "The `ai` block `name` of the document: `{:step <describe step> :prose <text> :header <text before the first step>
  :lines [..] :described d}`. Throws `generate/unparsable` (the document does not parse) or `generate/no-such-block`."
  [text path name]
  (let [d (parse/describe text :path path :kinds (kinds/registry))
        _ (when (seq (:errors d))
            (fail :generate/unparsable (str "the scenario does not parse: line " (:line (first (:errors d))) ": " (:message (first (:errors d))))
                  :line (:line (first (:errors d))) :hint "fix the file first; scenario.parse shows the error"))
        blocks (filterv #(= "ai" (:kind %)) (:steps d))
        blk (first (filter #(= name (:name %)) blocks))
        _ (when-not blk
            (fail :generate/no-such-block
                  (if (seq blocks)
                    (str "no ai block named " (pr-str name) "; the file has: " (str/join ", " (map #(or (:name %) "(unnamed)") blocks)))
                    (str "the scenario has no ai block (### ai <name> and the prose under it)"))
                  :known (vec (keep :name blocks)) :hint "a block is `### ai <name>` followed by prose"))
        lines (split-keep text)
        first-head (:line (first (:steps d)))
        prose (->> (subvec lines (:line blk) (get-in blk [:ai :prose-end-line]))
                   (drop-while str/blank?) join-keep str/trim)]
    (when (str/blank? prose)
      (fail :generate/empty-prose (str "the ai block " name " has no prose under it") :hint "write what the steps should do under the ### ai line"))
    {:step blk :prose prose :lines lines :described d
     :header (str/trimr (join-keep (subvec lines 0 (dec first-head))))}))

(defn splice
  "`text` with `region` (a vector of lines: marker, steps, `#< end`) in place of the region of `block` (a `describe` ai step),
  or after its prose when it has none."
  [text block region]
  (let [lines (split-keep text)
        {:keys [prose-end-line] r :region} (:ai block)]
    (join-keep
     (if r
       (vec (concat (subvec lines 0 (dec (:from-line r))) region (subvec lines (:to-line r))))
       (let [after (subvec lines prose-end-line)
             next-line (first after)]
         (vec (concat (subvec lines 0 prose-end-line) [""] region
                      (when (and (some? next-line) (not (str/blank? next-line))) [""])
                      after)))))))

;; the prompt and the answer ----------------------------------------------------------------------

(defn- skill-text [] (slurp (io/resource "deliberator/skills/scenario-steps.md") :encoding "UTF-8"))

(defn- headline [file name prose]
  (let [l (first (str/split-lines prose))]
    (str "Write Deliberator steps for the block " name " of " (.getName (io/file (str file))) ": "
         (if (> (count l) 110) (str (subs l 0 107) "...") l))))

(defn prompt-1 [file name prose header]
  (str (headline file name prose) "\n\n"
       (skill-text) "\n"
       "## The request\n\n"
       "Block `" name "` of `" (.getName (io/file (str file))) "`. The file's header, which the steps can use (variables):\n\n"
       "```\n" (if (str/blank? header) "(none)" header) "\n```\n\n"
       "The description to turn into steps:\n\n" prose "\n\n"
       "Now Read `universal.json` here, Read the skills that fit, and answer with the steps only.\n"))

(defn prompt-2 [first-prompt answer errors]
  (str first-prompt "\n## Your previous answer\n\n```\n" answer "\n```\n\n"
       "## Deliberator's checker found these errors in it (lines count from the first line of your answer)\n\n"
       (str/join "\n" (for [{:keys [line message]} errors] (str "- line " line ": " message)))
       "\n\nWrite the complete corrected steps, same rules, steps only.\n"))

(defn strip-fence
  "The answer without a surrounding code fence and blank edges, newline-terminated."
  [^String s]
  (let [lines (str/split-lines (str s))
        lines (vec (drop-while str/blank? lines))
        lines (vec (reverse (drop-while str/blank? (reverse lines))))
        fenced? (and (>= (count lines) 2) (str/starts-with? (first lines) "```") (= "```" (str/trim (peek lines))))
        lines (if fenced? (subvec lines 1 (dec (count lines))) lines)]
    (str (str/join "\n" lines) "\n")))

(defn check-answer
  "Checks `answer` (steps text) as the steps of a document whose header is `header`: -> `{:ok? :steps n :errors [{:line :message}]}`
  with lines relative to the answer (the engine's `check`, plus: the answer starts with a step, has no `ai` block and no
  region marker lines)."
  [ws e answer header path check-target]
  (let [prefix (str (when-not (str/blank? header) (str header "\n")) "\n")
        offset (count (filter #(= \newline %) prefix))
        answer-lines (str/split-lines answer)
        lead (first (remove str/blank? answer-lines))
        pre (cond-> []
              (not (and lead (re-matches #"### +[A-Za-z].*" lead)))
              (conj {:line 1 :message (str "the answer must start with a step line (### kind ...); it starts with "
                                           (pr-str (some-> lead (subs 0 (min 60 (count lead))))))}))
        local (vec (concat
                    (keep-indexed (fn [i l] (when (re-matches #"### +ai(\s.*)?" l) {:line (inc i) :message "an `ai` block is not a step: write the steps themselves"})) answer-lines)
                    (keep-indexed (fn [i l] (when (re-matches #"#[<>].*" l) {:line (inc i) :message "no `#>` / `#<` lines: Deliberator writes those"})) answer-lines)))]
    (if (seq pre)
      {:ok? false :steps 0 :errors pre}
      (let [r (engine/check ws e (.getBytes ^String (str prefix answer) "UTF-8") :path path :check-target check-target)
            errs (vec (concat local
                              (for [{:keys [line message]} (:errors r)
                                    :let [rel (when line (- line offset))]]
                                (if (and rel (pos? rel))
                                  {:line rel :message message}
                                  {:line (or line 1) :message (str "in the file header: " message)}))))
            errs (vec (sort-by :line errs))]
        {:ok? (and (empty? errs) (pos? (:steps r))) :steps (:steps r) :errors errs}))))

;; the model --------------------------------------------------------------------------------------

(defn- run-dir!
  "sessions/<key>/generate/<stamp>-<name>, created; -> Path."
  [ws sess name]
  (let [root (.resolve (session/dir ws sess) "generate")
        safe (let [s (str/replace (str name) #"[^A-Za-z0-9._-]+" "-")] (if (str/blank? s) "block" (subs s 0 (min 48 (count s)))))
        base (str (.format stamp (store/now)) "-" safe)]
    (Files/createDirectories root (make-array FileAttribute 0))
    (loop [n 1]
      (let [p (.resolve root (if (= n 1) base (str base "-" n)))]
        (if (try (Files/createDirectory p (make-array FileAttribute 0)) true
                 (catch FileAlreadyExistsException _ false))
          p
          (recur (inc n)))))))

(defn- persist!
  "Bytes into the raw store first, then a hard link in `dir` as `fname`; -> the sha."
  [ws ^Path dir fname ^bytes bs content-type op]
  (let [put (store/raw-put! ws bs {:source :ai :op op :env nil :at (store/now) :content-type content-type})]
    (store/link! ws (:sha put) (.resolve dir ^String fname))
    (:sha put)))

(defn- run-model!
  "Runs the model command once: the prompt file is its stdin, stdout and stderr go to files in `dir` as they arrive; those
  files are adopted into the raw store when the process ends, before anything reads them. -> `{:exit :out :err :took-ms}`."
  [ws {:keys [command env budget-ms]} ^Path dir ^Path ctx-dir n on-cancel!]
  (let [out (.toFile (.resolve dir (str "model-" n ".out")))
        err (.toFile (.resolve dir (str "model-" n ".err")))
        pb (doto (ProcessBuilder. ^java.util.List (mapv str command))
             (.directory (.toFile ctx-dir))
             (.redirectInput (.toFile (.resolve dir (str "prompt-" n ".md"))))
             (.redirectOutput out)
             (.redirectError err))
        _ (.putAll (.environment pb) ^java.util.Map (into {} (map (fn [[k v]] [(str k) (str v)])) env))
        t0 (System/nanoTime)
        p (try (.start pb)
               (catch java.io.IOException e
                 (fail :generate/cannot-start (str "cannot run the model command " (first command) ": " (.getMessage e))
                       :command (first command)
                       :hint "workspace.edn :ai :command names it (default: claude, logged in on the subscription)")))
        killed (atom nil)
        kill! (fn [why] (when (compare-and-set! killed nil why) (process/kill-tree! p)))
        _ (when on-cancel! (on-cancel! #(kill! :cancelled)))
        done? (try (.waitFor p (long (or budget-ms 240000)) TimeUnit/MILLISECONDS)
                   (catch InterruptedException e (kill! :cancelled) (throw e)))
        _ (when-not done? (kill! :timeout) (.waitFor p))
        took (quot (- (System/nanoTime) t0) 1000000)
        adopt (fn [^java.io.File f ct]
                (when (pos? (.length f))
                  (store/raw-adopt! ws f {:source :ai :op (str "model " (first command)) :env nil :at (store/now) :content-type ct})))]
    (adopt out "text/plain")
    (adopt err "text/plain")
    (case @killed
      :cancelled (fail :generate/cancelled "the model call was cancelled")
      :timeout (fail :generate/timeout (str "the model command ran longer than " (quot (or budget-ms 240000) 1000) " s and was killed")
                     :hint "workspace.edn :ai :budget-ms raises it")
      {:exit (.exitValue p) :out out :err err :took-ms took})))

(defn- parse-claude
  "The `--output-format json` document: -> `{:answer :usage :model :session-id :cost-usd :duration-ms :turns}` or throws."
  [text]
  (let [d (try (json/read-str text) (catch Exception _ nil))]
    (when-not (map? d)
      (fail :generate/bad-model-output "the model command did not print the JSON document of --output-format json"
            :hint "model-N.out in the run folder holds what it printed; workspace.edn :ai :format :text takes a bare answer"))
    (when (get d "is_error")
      (fail :generate/model-error (str "the model reported an error: " (str (get d "result") (when-let [s (get d "subtype")] (str " (" s ")"))))))
    (let [u (get d "usage") mu (get d "modelUsage")
          in (when u (+ (long (get u "input_tokens" 0)) (long (get u "cache_creation_input_tokens" 0)) (long (get u "cache_read_input_tokens" 0))))]
      {:answer (str (get d "result"))
       :model (or (first (keys mu)) "claude")
       :session-id (get d "session_id")
       :usage (when u {:input in :output (long (get u "output_tokens" 0))
                       :input-fresh (long (get u "input_tokens" 0))
                       :cache-read (long (get u "cache_read_input_tokens" 0))
                       :cache-write (long (get u "cache_creation_input_tokens" 0))
                       :cost-usd (get d "total_cost_usd") :turns (get d "num_turns") :duration-ms (get d "duration_ms")})})))

(defn- model-name [command]
  (let [i (.indexOf ^java.util.List (vec command) "--model")]
    (if (and (>= i 0) (< (inc i) (count command))) (nth command (inc i)) (first command))))

;; marker -----------------------------------------------------------------------------------------

(defn- n-fmt [n] (str/replace (str n) #"\B(?=(\d{3})+(?!\d))" " "))

(defn marker
  "The `#> generated by ...` line: model, tokens, cost, time and the run folder (relative to the workspace)."
  [{:keys [model usage attempts took-ms run]}]
  (str "#> generated by " model
       (if usage
         (str " · " (n-fmt (:input usage)) " tokens in"
              (when (pos? (long (:cache-read usage 0))) (str " (" (n-fmt (:cache-read usage)) " cached)"))
              ", " (n-fmt (:output usage)) " out"
              (when (some? (:cost-usd usage)) (str " · $" (format "%.4f" (double (:cost-usd usage))))))
         " · usage not reported")
       " · " (format "%.1f" (/ (double took-ms) 1000)) " s"
       (when (> attempts 1) (str " · " attempts " attempts"))
       " · " run))

(defn- sum-usage [us]
  (when (seq (filter some? us))
    (let [us (filter some? us)]
      {:input (reduce + (map :input us)) :output (reduce + (map :output us))
       :input-fresh (reduce + (map :input-fresh us)) :cache-read (reduce + (map :cache-read us)) :cache-write (reduce + (map :cache-write us))
       :cost-usd (when (every? some? (map :cost-usd us)) (reduce + (map :cost-usd us)))
       :turns (reduce + (keep :turns us))})))

;; the whole ------------------------------------------------------------------------------------

(defn generate!
  [ws {:keys [file text name session operations sink on-cancel! write?] envr :env}]
  (let [emit! (fn [m] (when sink (sink m)))
        src (or text (slurp (io/file (str file)) :encoding "UTF-8"))
        {:keys [step prose header]} (find-block src file name)
        ai (ai-config ws)
        dir (run-dir! ws session name)
        ctx-dir (.resolve dir "context")
        rel (str "sessions/" (store/safe-name session) "/generate/" (.getFileName dir))
        started (store/now)
        t-start (System/nanoTime)
        _ (persist! ws dir "source.scn" (.getBytes ^String src "UTF-8") "text/plain" (str "scenario.generate " name))
        built (universal/build ws (:name envr) {:operations operations})
        uni (universal/write! ctx-dir built)
        summary! (fn [m] (store/write-edn! (.resolve dir "generate.edn")
                                           (merge {:name name :scenario (str file) :sha256 (store/sha256 (.getBytes ^String src "UTF-8"))
                                                   :env (:name envr) :session session :started started :run rel
                                                   :command (first (:command ai)) :format (:format ai)}
                                                  m)))
        _ (summary! {:status :running})
        _ (emit! {:event :generate.started :name name :run rel :universal (:path uni) :skills (:skills uni)})
        check-target (fn [k] (denv/target envr (keyword k)))
        p1 (prompt-1 file name prose header)]
    (loop [n 1 prompt p1 prev nil used []]
      (emit! {:event :generate.attempt :attempt n})
      (persist! ws dir (str "prompt-" n ".md") (.getBytes ^String prompt "UTF-8") "text/markdown" (str "scenario.generate prompt " n))
      (let [r (try (run-model! ws ai dir ctx-dir n on-cancel!)
                   (catch clojure.lang.ExceptionInfo e
                     (summary! {:status :failed :error (ex-message e) :attempts n}) (throw e)))
            out-text (slurp (:out r) :encoding "UTF-8")
            err-text (slurp (:err r) :encoding "UTF-8")
            _ (when (and (not (zero? (:exit r))) (not (and (= :claude-json (:format ai)) (str/starts-with? (str/trim out-text) "{"))))
                (summary! {:status :failed :error (str "model command exit " (:exit r)) :attempts n})
                (fail :generate/model-failed (str "the model command exited " (:exit r) (when-not (str/blank? err-text) (str ": " (subs err-text 0 (min 300 (count err-text))))))
                      :exit (:exit r) :run (str dir) :hint (str "model-" n ".out and .err in the run folder hold what it printed")))
            parsed (try (if (= :claude-json (:format ai))
                          (parse-claude out-text)
                          {:answer out-text :model (model-name (:command ai)) :usage nil})
                        (catch clojure.lang.ExceptionInfo e
                          (summary! {:status :failed :error (ex-message e) :attempts n}) (throw (ex-info (ex-message e) (assoc (ex-data e) :run (str dir)) e))))
            answer (strip-fence (:answer parsed))
            _ (persist! ws dir (str "answer-" n ".scn") (.getBytes ^String answer "UTF-8") "text/plain" (str "scenario.generate answer " n))
            _ (store/write-edn! (.resolve dir (str "usage-" n ".edn")) (assoc (select-keys parsed [:model :usage :session-id]) :took-ms (:took-ms r) :exit (:exit r)))
            chk (check-answer ws envr answer header file check-target)
            _ (store/write-edn! (.resolve dir (str "check-" n ".edn")) (select-keys chk [:ok? :steps :errors]))
            _ (emit! {:event :generate.checked :attempt n :ok (:ok? chk) :errors (count (:errors chk))})
            used (conj used (assoc parsed :took-ms (:took-ms r) :answer answer))]
        (cond
          (:ok? chk)
          (let [usage (sum-usage (map :usage used))
                took-ms (quot (- (System/nanoTime) t-start) 1000000)
                mk (marker {:model (:model parsed) :usage usage :attempts n :took-ms (reduce + (map :took-ms used)) :run rel})
                region (vec (concat [mk] (str/split-lines answer) ["#< end"]))
                new-text (splice src step region)
                _ (persist! ws dir "generated.scn" (.getBytes ^String answer "UTF-8") "text/plain" (str "scenario.generate steps " name))
                wrote (when (and write? file)
                        (store/write-bytes-atomic! (->path file) (.getBytes ^String new-text "UTF-8")) true)
                res {:status "ok" :name name :model (:model parsed) :attempts n :usage usage :steps (:steps chk)
                     :file (some-> file str) :marker mk :region region :run rel :took-ms took-ms :session-id (:session-id parsed)
                     :wrote (boolean wrote)
                     :paths {:run (str dir) :universal (:path uni) :generated (str (.resolve dir "generated.scn"))
                             :summary (str (.resolve dir "generate.edn"))}}]
            (summary! (merge (dissoc res :region :paths) {:status :ok :finished (store/now) :generated-sha256 (store/sha256 (.getBytes ^String answer "UTF-8"))}))
            (emit! {:event :generate.finished :status "ok" :steps (:steps chk) :run rel})
            res)

          (< n 2)
          (recur (inc n) (prompt-2 p1 answer (:errors chk)) answer used)

          :else
          (do (summary! {:status :invalid :attempts n :errors (:errors chk) :finished (store/now)
                         :usage (sum-usage (map :usage used)) :model (:model parsed) :session-id (:session-id parsed)})
              (emit! {:event :generate.finished :status "invalid" :run rel})
              (fail :generate/invalid
                    (str "the model's steps failed the check twice: "
                         (str/join "; " (for [{:keys [line message]} (take 3 (:errors chk))] (str "line " line ": " message))))
                    :errors (:errors chk) :run (str dir) :path (str (.resolve dir "answer-2.scn"))
                    :hint "the prompts, answers and errors are in the run folder; nothing was put in the file")))))))
