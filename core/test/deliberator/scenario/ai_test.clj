(ns deliberator.scenario.ai-test
  "The `ai` block: marker lines are layout, the kind is inert, the engine skips it and keeps the numbers,
  `check` collects every error."
  (:require [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [deliberator.daemon]   ; registers every step kind
            [deliberator.env :as env]
            [deliberator.generate :as generate]
            [deliberator.scenario.engine :as engine]
            [deliberator.scenario.kinds :as kinds]
            [deliberator.scenario.parse :as parse]
            [deliberator.test-util :as tu])
  (:import (java.nio.charset StandardCharsets)))

(def doc
  (str "# @env local\n# @var corr = c-{{uuid}}\n\n"
       "### ai activate\nSend an order to the inbox,\nthen wait until it is acked.\n\n"
       "#> generated by haiku · 10 tokens in, 2 out · $0.0010 · 1.0 s · sessions/T/generate/x\n"
       "### sqs send queue/inbox send-order\n# @attr id={{uuid}}\n{\"orderId\": \"1\"}\n\n"
       "### dynamodb get table/messages stored\n# @until $.Item.status.S == ACKED within 10s\n{\"Key\": {\"id\": {\"S\": \"1\"}}}\n"
       "#< end\n\n"
       "### wait pause\n# @for 1s\n"))

(defn- thrown [text]
  (try (parse/parse text :kinds (kinds/registry)) nil
       (catch clojure.lang.ExceptionInfo e (ex-data e))))

(deftest markers-are-layout
  (let [{:keys [steps markers]} (parse/parse doc :kinds (kinds/registry))
        [ai sqs ddb wait] steps
        body #(some-> % :body (String. StandardCharsets/UTF_8))]
    (is (= ["ai" "sqs" "dynamodb" "wait"] (map :kind steps)))
    (is (= "Send an order to the inbox,\nthen wait until it is acked.\n" (body ai)) "the prose stops at the marker")
    (is (= "{\"orderId\": \"1\"}\n" (body sqs)))
    (is (= "{\"Key\": {\"id\": {\"S\": \"1\"}}}\n" (body ddb)) "the end marker is not part of the last step's body")
    (is (nil? (body wait)))
    (is (= [{:line 8 :open? true} {:line 16 :open? false}] (map #(select-keys % [:line :open?]) markers)))
    (is (= "#< end" (:text (second markers))))))

(deftest describe-tells-where-the-region-is
  (let [d (parse/describe doc :kinds (kinds/registry))
        ai (first (:steps d))]
    (is (empty? (:errors d)))
    (is (= {:prose-end-line 6 :region {:from-line 8 :to-line 16 :header "#> generated by haiku · 10 tokens in, 2 out · $0.0010 · 1.0 s · sessions/T/generate/x"}}
           (:ai ai)))
    (is (nil? (:ai (second (:steps d)))) "only ai steps have it"))
  (testing "an ai block without steps: where its prose ends"
    (let [d (parse/describe "### ai a\nfirst\nsecond\n\n\n### wait w\n" :kinds (kinds/registry))]
      (is (= {:prose-end-line 3} (:ai (first (:steps d))))))))

(deftest markers-must-pair
  (is (re-find #"never closed" (:message (thrown "### ai a\nx\n#> m\n### wait w\n"))))
  (is (re-find #"without an open" (:message (thrown "### wait w\n#< end\n"))))
  (is (re-find #"not closed yet" (:message (thrown "### ai a\n#> m\n### wait w\n#> again\n#< end\n"))))
  (let [e (thrown "### ai a\nx\n#> m\n### wait w\n#< end\nstray text\n### wait z\n")]
    (is (= 6 (:line e)))
    (is (re-find #"after `#< end`" (:message e)))))

(deftest a-marker-inside-a-json-string-is-body
  (let [t "### http h\nPOST http://x/\n\n{\"a\": \"line one\n#> not a marker\n#< neither\nline two\"}\n"
        {:keys [steps markers]} (parse/parse t :kinds (kinds/registry))]
    (is (empty? markers))
    (is (str/includes? (String. ^bytes (:body (first steps)) StandardCharsets/UTF_8) "#> not a marker"))))

(deftest ai-is-an-inert-kind
  (let [k (first (filter #(= "ai" (:kind %)) (kinds/describe-kinds)))]
    (is (true? (:inert k)))
    (is (false? (:inert (first (filter #(= "wait" (:kind %)) (kinds/describe-kinds))))))))

(defn- scn-file [text]
  (let [f (java.io.File/createTempFile "ai-test" ".scn" (doto (java.io.File. (System/getProperty "user.dir") "target") .mkdirs))]
    (.deleteOnExit f)
    (spit f text)
    f))

(deftest the-engine-skips-ai-blocks-and-keeps-the-numbers
  (tu/with-temp-home
    (let [e (env/load "default" "local")
          p (engine/plan "default" e (str (scn-file doc)) :resolve-target #(env/target e (keyword %)))]
      (is (= [2 3 4] (map :n (:steps p))) "the ai block is step 1, the others keep their places")
      (is (= ["sqs" "dynamodb" "wait"] (map :kind (:steps p)))))
    (let [e (env/load "default" "local")]
      (is (re-find #"only ai blocks" (ex-message (try (engine/plan "default" e (str (scn-file "### ai a\nprose\n")))
                                                      (catch clojure.lang.ExceptionInfo x x)))))
      (is (re-find #"is an ai block" (ex-message (try (engine/plan "default" e (str (scn-file doc)) :steps [1]
                                                                  :resolve-target #(env/target e (keyword %)))
                                                      (catch clojure.lang.ExceptionInfo x x))))))))

(deftest check-collects-every-error
  (tu/with-temp-home
    (let [e (env/load "default" "local")
          chk (fn [t] (engine/check "default" e (.getBytes ^String t "UTF-8") :check-target #(env/target e (keyword %))))
          errs (fn [t] (:errors (chk t)))]
      (testing "a good document"
        (is (empty? (errs doc)))
        (is (= 3 (:steps (chk doc)))))
      (testing "an unknown target written bare on the step line"
        (let [r (errs "### sqs send queue/inboxx x\n{}\n")]
          (is (= 1 (count r)))
          (is (= 1 (:line (first r))))
          (is (re-find #"unknown target" (:message (first r))))))
      (testing "an unknown kind is a parse error, one"
        (is (re-find #"unknown step kind" (:message (first (errs "### sqz send queue/inbox\n{}\n"))))))
      (testing "an unknown directive is a parse error"
        (is (re-find #"unknown directive @bogus" (:message (first (errs "### wait w\n# @bogus 1\n"))))))
      (testing "several step errors at once: variable, assert syntax, target"
        (let [r (errs (str "### sqs send queue/inbox a\n{\"x\": \"{{nope}}\"}\n\n"
                           "### wait b\n# @assert elapsed >>> 3\n\n"
                           "### dynamodb get table/nothing c\n{}\n"))]
          (is (= [1 5 7] (map :line r)) (pr-str r))
          (is (not-any? #(re-find #"^line \d" (:message %)) r) "no document line numbers in the messages")))
      (testing "an unknown target inside {{ }} is caught as well"
        (is (re-find #"unknown target" (:message (first (errs "### http h\nGET {{service/zz}}/x\n"))))))
      (testing "nothing but a header is an error"
        (is (re-find #"no steps" (:message (first (errs "# @env local\n")))))))))

(deftest splice-replaces-or-inserts
  (let [region ["#> generated by m" "### wait x" "# @for 1s" "#< end"]
        d (parse/describe doc :kinds (kinds/registry))
        ai (first (:steps d))
        out (generate/splice doc ai region)]
    (testing "replaces the region of the block"
      (is (not (str/includes? out "sqs send")))
      (is (str/includes? out "#> generated by m\n### wait x\n# @for 1s\n#< end\n\n### wait pause"))
      (let [d2 (parse/describe out :kinds (kinds/registry))]
        (is (empty? (:errors d2)))
        (is (= ["ai" "wait" "wait"] (map :kind (:steps d2))))))
    (testing "again: same result (generating twice replaces, never stacks)"
      (is (= out (generate/splice out (first (:steps (parse/describe out :kinds (kinds/registry)))) region))))
    (testing "inserts after the prose of a block that has none, a blank line before and after"
      (let [t "# @env local\n\n### ai a\nprose one\nprose two\n\n### wait w\n# @for 1s\n"
            ai (first (:steps (parse/describe t :kinds (kinds/registry))))
            out (generate/splice t ai region)]
        (is (= "# @env local\n\n### ai a\nprose one\nprose two\n\n#> generated by m\n### wait x\n# @for 1s\n#< end\n\n### wait w\n# @for 1s\n" out))))
    (testing "a block directly followed by a step gets a blank line after the region"
      (let [t "### ai a\nprose\n### wait w\n"
            ai (first (:steps (parse/describe t :kinds (kinds/registry))))]
        (is (= "### ai a\nprose\n\n#> generated by m\n### wait x\n# @for 1s\n#< end\n\n### wait w\n" (generate/splice t ai region)))))))
